def deflate_to_2015(sales_nominal_usd: float,
                    deflator: float = DEFAULT_DEFLATOR_2025_TO_2015) -> float:
    """현재 명목 매출(USD, 원 단위) -> 2015년 달러 기준 백만 단위."""
    if sales_nominal_usd <= 0:
        raise ValueError(f"매출은 0보다 커야 함: {sales_nominal_usd}")
    return sales_nominal_usd / 1e6 / deflator


def nominal_to_real(nominal_growth: float,
                    inflation: float = DEFAULT_INFLATION) -> float:
    """
    명목 성장률(소수) -> 실질 성장률(소수).

    ⚠️ 이 변환을 빼먹으면 인플레율만큼 조용히 낙관적으로 비교된다 - base rate
    표가 실질이기 때문. v3.35 실질/명목 EPS 함정과 같은 계열이다.
    """
    return (1.0 + nominal_growth) / (1.0 + inflation) - 1.0


def size_class_for(sales_2015_usd_mn: float) -> str:
    """2015년 달러 기준 매출(백만) -> base rate 표의 규모 구간 키."""
    for lo, hi, key in SIZE_CLASSES:
        if lo <= sales_2015_usd_mn < hi:
            return key
    raise ValueError(f"규모 구간을 찾을 수 없음: {sales_2015_usd_mn}")


def base_rate_at_least(size_class: str, real_growth_pct: float,
                       horizon_years: int = 10) -> float:
    """
    해당 규모 구간에서 `real_growth_pct`(실질, 퍼센트) **이상**의 CAGR을
    horizon_years 동안 달성한 기업 비율(%).

    구간 경계에 걸치면 그 구간 전체를 포함한다(보수적 - 실제보다 높게 나옴).
    """
    if size_class not in SALES_GROWTH_BASE_RATES:
        raise ValueError(f"알 수 없는 규모 구간: {size_class}")
    if horizon_years not in HORIZONS:
        raise ValueError(
            f"지원하지 않는 구간: {horizon_years} (가능: {sorted(HORIZONS)})")
    col = HORIZONS[horizon_years]
    table = SALES_GROWTH_BASE_RATES[size_class]
    total = 0.0
    for name, lo, hi in GROWTH_BINS:
        if hi > real_growth_pct:      # 이 구간의 일부라도 목표 이상이면 포함
            total += table[name][col]
    return round(total, 2)


def median_growth(size_class: str, horizon_years: int = 10) -> float:
    """
    해당 규모 구간의 중앙값 성장률(실질, 퍼센트) 근사.

    ⚠️ 원문 표의 Mean/Median 행을 직접 옮기지 않고 구간 분포에서 보간한다 -
    파싱 검증이 끝난 16개 행만 신뢰한다는 뜻이다(요약통계 행은 파서 검증
    범위 밖이었다). 구간 폭이 5%p라 최대 오차도 그 정도다.
    """
    col = HORIZONS[horizon_years]
    table = SALES_GROWTH_BASE_RATES[size_class]
    cum = 0.0
    for name, lo, hi in GROWTH_BINS:
        share = table[name][col]
        if cum + share >= 50.0:
            if share <= 0:
                return lo
            frac = (50.0 - cum) / share
            lo_b = lo if lo != float("-inf") else -30.0
            hi_b = hi if hi != float("inf") else 50.0
            return round(lo_b + frac * (hi_b - lo_b), 2)
        cum += share
    return float("nan")


#: base rate를 서술 라벨로 옮기는 구간.
#: ⚠️ 0.0("역사적 선례 없음")만 사실 진술이고 나머지는 편의상 라벨이다.
PLAUSIBILITY_TIERS = (
    (0.0, "NO_PRECEDENT", "이 규모 구간에서 해당 성장률을 그 기간 유지한 기업이 표본에 없다"),
    (1.0, "EXTREMELY_RARE", "100곳 중 1곳 미만"),
    (5.0, "RARE", "20곳 중 1곳 미만"),
    (20.0, "UNCOMMON", "5곳 중 1곳 미만"),
    (float("inf"), "COMMON", "드물지 않음"),
)


def assess_growth_plausibility(sales_nominal_usd: float,
                               growth_nominal: float,
                               horizon_years: int = 10,
                               inflation: float = DEFAULT_INFLATION,
                               deflator: float = DEFAULT_DEFLATOR_2025_TO_2015) -> dict:
    """
    "이 회사에 부여한 성장률이 역사적으로 얼마나 흔한가"를 되돌려준다.

    **판정하지 않는다.** 탈락시키지도, 성장률을 고치지도 않는다 - Mauboussin
    자신의 처방("reality check")이자 IRS의 병기 원칙이다.

    sales_nominal_usd: 최근 회계연도 매출(USD 원 단위. 외화면 미리 환산할 것)
    growth_nominal:    부여한 성장률(소수, 명목)
    """
    sales_2015 = deflate_to_2015(sales_nominal_usd, deflator)
    size_class = size_class_for(sales_2015)
    real_pct = nominal_to_real(growth_nominal, inflation) * 100.0
    rate = base_rate_at_least(size_class, real_pct, horizon_years)
    tier, note = next((t, n) for cut, t, n in PLAUSIBILITY_TIERS if rate <= cut)
    return {
        "sales_2015_usd_mn": round(sales_2015, 1),
        "size_class": size_class,
        "growth_nominal_pct": round(growth_nominal * 100, 2),
        "growth_real_pct": round(real_pct, 2),
        "horizon_years": horizon_years,
        "base_rate_pct": rate,
        "tier": tier,
        "tier_note": note,
        "peer_median_real_pct": median_growth(size_class, horizon_years),
        "inflation_assumed": inflation,
        "source": "Credit Suisse HOLT / Mauboussin & Callahan, Base Rate Book (2016-09-26)",
        "caveat": (
            "과거 빈도이지 미래 확률이 아니다. 표는 실질 기준이라 명목 성장률을 "
            f"인플레 {inflation*100:.1f}% 가정으로 환산해 비교했다."
        ),
    }


#: 규모 조건부 성장상한이 허용하는 최소 base rate(%).
#: ⚠️ **이 컷은 검증된 값이 아니다.** Mauboussin은 분포를 보라고 했지 어느
#: base rate에서 "과도한 낙관"으로 부를지는 주지 않았다. 1.0%는 "100곳 중
#: 1곳은 해냈다"는 서술적 기준이며, 2026-08-23 사용자 승인으로 채택됐다
#: (승인 시점 실측 영향: PDD·PGR·SE 3종목, 매수비중 28.46%, SE가 S→A 강등).
#: 값을 바꾸면 즉시 자본이 재배분되므로 임의 조정 금지.
MIN_BASE_RATE_FOR_CAP = 1.0


def size_conditioned_growth_cap(sales_nominal_usd: float,
                                min_base_rate_pct: float = MIN_BASE_RATE_FOR_CAP,
                                horizon_years: int = 10,
                                inflation: float = DEFAULT_INFLATION,
                                deflator: float = DEFAULT_DEFLATOR_2025_TO_2015) -> dict:
    """
    이 회사 **규모**에서 역사적으로 최소 `min_base_rate_pct`% 이상의 기업이
    달성한 가장 높은 성장률(명목, 소수)을 돌려준다.

    왜 필요한가: `LYNCH_TYPE_CAPS`의 fast_grower 25%는 린치 원저서의 분류
    기술어에서 왔는데(2026-08-23 확인), 린치는 그 유형을 **"small, aggressive
    companies"**로 한정했다. IRS는 그 조건을 떨어뜨리고 규모와 무관하게
    적용했고, 그 결과 같은 25%의 10년 base rate가 DUOL($1.0B) 3.5% vs
    PDD($60B) 0.2%로 17.5배 갈렸다.

    ⚠️ 반환값은 **명목**이다(표는 실질이므로 내부에서 환산한다). Realistic
    Growth가 명목이라 그대로 비교할 수 있어야 하기 때문 - 이 변환을 호출측에
    맡기면 v3.35 실질/명목 함정이 재발한다.
    """
    sales_2015 = deflate_to_2015(sales_nominal_usd, deflator)
    size_class = size_class_for(sales_2015)
    best_real = None
    for name, lo, hi in GROWTH_BINS:
        if lo == float("-inf"):
            continue
        if base_rate_at_least(size_class, lo, horizon_years) >= min_base_rate_pct:
            best_real = lo
    if best_real is None:
        # 어떤 성장률도 컷을 못 넘기는 경우(이론상) - 캡을 걸지 않는다.
        return {"cap_nominal": None, "size_class": size_class,
                "cap_real_pct": None, "min_base_rate_pct": min_base_rate_pct,
                "note": "이 규모 구간에서 컷을 넘는 성장구간이 없어 캡 미적용"}
    cap_nominal = (1.0 + best_real / 100.0) * (1.0 + inflation) - 1.0
    return {
        "cap_nominal": cap_nominal,
        "cap_real_pct": best_real,
        "size_class": size_class,
        "sales_2015_usd_mn": round(sales_2015, 1),
        "min_base_rate_pct": min_base_rate_pct,
        "base_rate_at_cap_pct": base_rate_at_least(size_class, best_real, horizon_years),
        "horizon_years": horizon_years,
        "inflation_assumed": inflation,
        "note": (
            f"매출규모 {size_class} 구간에서 실질 {best_real:.0f}% 이상을 "
            f"{horizon_years}년간 유지한 기업이 "
            f"{base_rate_at_least(size_class, best_real, horizon_years):.1f}%"
            f"(컷 {min_base_rate_pct}% 이상)라 명목 {cap_nominal*100:.2f}%를 상한으로 둔다"
        ),
    }


