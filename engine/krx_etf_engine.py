"""
KRX 래퍼 ETF 엔진 (v3.38 신설, 2026-08-07)

**경위**: 사용자가 이 ETF 엔진을 만든 실제 목적이 한국 ISA 계좌에서 살 ETF를
찾는 것이었다 - ISA 계좌는 국내 상장 ETF만 매수 가능하므로, v3.33~v3.37에서
분석한 VOO/QQQ/DIA/XLE/XLU/IWM 같은 **미국 상장 ETF 자체는 매수 대상이 아니다.**
실제 매수 대상은 그 지수를 추종하는 **국내 상장 ETF**(TIGER/KODEX/ACE 미국S&P500
등)다.

**핵심 통찰 - 밸류에이션은 재계산하지 않는다**: 국내 상장 추종형 ETF는 미국
원본과 **같은 주식 바스켓**을 담는다. P/E와 이익성장률은 화폐 표시와 무관한
값이다 - 원화 환산은 분자(주가)와 분모(주당순이익)에 동일하게 적용되므로 P/E
자체는 변하지 않는다(환헤지형이든 환노출형이든 마찬가지 - 헤지는 환노출을
없앨 뿐 기초자산의 밸류에이션에는 영향을 주지 않는다). 따라서 같은 지수를
추종하는 국내 ETF는 `run_etf_analysis()`로 이미 계산한 미국 원본의 P/E·성장률·
위험점수를 **그대로 재사용**하고, 국내 상장분 고유의 값(총보수·환헤지·순자산)만
새로 반영한다. 밸류에이션 로직을 복제하지 않는다 - Simplicity First가 반복
경고한 "중복 계산이 두 계산을 미묘하게 어긋나게 만든다"는 함정을 피하기 위함.

**재사용하지 않는 것 - 이 래퍼 고유의 비용/구조**:
  - **총보수**: 미국 원본(VOO 0.03%대)보다 국내 상장분이 대체로 높다(0.06~0.5%대,
    상품에 따라 편차가 크다). 이 차이는 확정 비용이라 `expense_ratio_delta()`로
    명시한다.
  - **환헤지 여부**: 헤지형(상품명 "(H)")은 환노출을 없애는 대신 금리차만큼의
    캐리비용이 발생한다(현재 미국 금리가 한국보다 높아 헤지가 구조적으로
    불리한 국면). 이 비용은 총보수처럼 고정값이 아니라 금리차에 따라 변동하므로
    **자동으로 Gap에 반영하지 않는다** - is_insurer/sbc_cross_check와 동일한
    "병기, 자동판정 안 함" 원칙.
  - **순자산/유동성**: 국내 상장분은 미국 원본 대비 훨씬 작은 경우가 많다
    (예: IWM $700억대 vs KODEX 미국러셀2000(H) 266억원) - 스프레드·상장폐지
    리스크에 영향을 주지만 밸류에이션 자체와는 무관하므로 병기만 한다.

**의도적으로 다루지 않는 것 - 레버리지/인버스/커버드콜/액티브 상품**: 이들은
기초지수를 그대로 추종하지 않아(레버리지는 일별 수익률을 배수로 복제해 장기
수익률이 지수 배수와 어긋나고, 커버드콜은 상방을 프리미엄과 맞바꾼다) 이 재사용
전제 자체가 깨진다. `KRXWrapperInputs.product_type`이 `"plain"`이 아니면 실행을
거부한다.
"""


def expense_ratio_delta(krx_expense_ratio: float, us_expense_ratio: float) -> float:
    """
    국내 상장 래퍼가 미국 원본보다 매년 추가로 부담하는 확정 비용(소수).

    음수가 나올 수도 있다(드물지만 국내 상품이 더 저렴한 경우) - 부호를 강제로
    양수로 만들지 않는다. 둘 다 0~1 소수 규약(퍼센트 숫자 주의).
    """
    if krx_expense_ratio < 0 or us_expense_ratio < 0:
        raise ValueError("expense_ratio는 0 이상의 소수여야 함(퍼센트 숫자 주의)")
    if krx_expense_ratio >= 0.03 or us_expense_ratio >= 0.03:
        raise ValueError(
            f"expense_ratio가 3% 이상이다(krx={krx_expense_ratio}, us={us_expense_ratio}) - "
            f"퍼센트 숫자를 소수 자리에 넣은 것으로 보인다(0.35% -> 0.0035)."
        )
    return krx_expense_ratio - us_expense_ratio


def hedge_cost_warning(hedged: bool, estimated_hedge_carry: float = None) -> str:
    """
    환헤지 비용에 대한 경고/안내 문구를 반환한다. 비헤지 상품이면 None.

    ⚠️ `estimated_hedge_carry`를 자동으로 추정하지 않는다 - 헤지 캐리비용은
    한미 단기금리차에 따라 시점마다 변하는 값이라, 이 프로젝트가 다른 논쟁적
    지표(Fed모델 스프레드, 보험업 P/B 임계값)를 다룰 때와 같은 원칙으로 **숫자를
    직접 주지 않고 분석자가 그때그때 판단하게 한다.**
    """
    if not hedged:
        return None
    if estimated_hedge_carry is None:
        return (
            "[환헤지 비용 미반영] 환헤지형 상품이라 환노출형과 달리 한미 단기금리차만큼의 "
            "캐리비용이 매년 발생하는데, 이 비용을 추정치로 넣지 않아 Gap·보수율차와 "
            "같은 축에서 비교되지 않았다. 현재(2026-08 기준) 미국 정책금리가 한국보다 "
            "높아 헤지가 구조적으로 불리한 국면이라는 점을 감안할 것."
        )
    return (
        f"[환헤지 비용 반영] 환헤지형 상품으로, 연 {estimated_hedge_carry*100:.2f}%p의 "
        f"캐리비용을 추정치로 병기한다(Gap에는 자동 반영하지 않음 - 분석자가 총보수차와 "
        f"함께 판단할 것)."
    )


